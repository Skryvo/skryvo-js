// Writes src/generated/ from spec/openapi.json: one type per schema and per answer, and the table of operations.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const PREFIX = "/api/v1/agent";
const spec = JSON.parse(readFileSync(new URL("../spec/openapi.json", import.meta.url), "utf8"));

// A spec name that would shadow a JavaScript global in users' code.
const RENAMED = { Error: "ErrorBody" };
const refName = (ref) => RENAMED[ref.split("/").pop()] ?? ref.split("/").pop();
const pascal = (id) => id.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

function tsType(schema, indent) {
  if (!schema || Object.keys(schema).length === 0) return "unknown";
  if (schema.$ref) return refName(schema.$ref);
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  const options = schema.anyOf || schema.oneOf;
  if (options) return [...new Set(options.map((o) => tsType(o, indent)))].join(" | ");
  if (Array.isArray(schema.type)) {
    return [...new Set(schema.type.map((type) => tsType({ ...schema, type }, indent)))].join(" | ");
  }
  switch (schema.type) {
    case "null":
      return "null";
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array": {
      const inner = tsType(schema.items, indent);
      return /[|&{]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
    }
    case "object":
      if (schema.properties && Object.keys(schema.properties).length) return objectBody(schema, indent);
      if (schema.additionalProperties && schema.additionalProperties !== true) {
        return `Record<string, ${tsType(schema.additionalProperties, indent)}>`;
      }
      return "Record<string, unknown>";
    default:
      return "unknown";
  }
}

function doc(text, indent) {
  if (!text) return "";
  return `${indent}/** ${text.replace(/\*\//g, "* /").replace(/\s+/g, " ").trim()} */\n`;
}

function objectBody(schema, indent) {
  const required = new Set(schema.required || []);
  const lines = Object.entries(schema.properties).map(([key, prop]) => {
    const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
    const optional = required.has(key) ? "" : "?";
    return `${doc(prop.description, indent + "  ")}${indent}  ${name}${optional}: ${tsType(prop, indent + "  ")};`;
  });
  return `{\n${lines.join("\n")}\n${indent}}`;
}

function declare(name, schema, description) {
  const body = tsType(schema, "");
  const head = doc(description, "");
  return body.startsWith("{") ? `${head}export interface ${name} ${body}\n` : `${head}export type ${name} = ${body};\n`;
}

const types = Object.entries(spec.components.schemas).map(([name, schema]) =>
  declare(RENAMED[name] ?? name, schema, schema.description),
);

const operations = [];
for (const [path, item] of Object.entries(spec.paths)) {
  if (!path.startsWith(PREFIX)) continue;
  for (const [method, op] of Object.entries(item)) {
    const ok = Object.keys(op.responses || {}).find((code) => code.startsWith("2"));
    const answer = op.responses?.[ok]?.content?.["application/json"]?.schema;
    const response = answer ? `${pascal(op.operationId)}Response` : null;
    if (answer) types.push(declare(response, answer, op.summary));
    const body = op.requestBody?.content?.["application/json"]?.schema;
    operations.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path: path.slice(PREFIX.length),
      summary: op.summary ?? "",
      body: body?.$ref ? refName(body.$ref) : null,
      query: (op.parameters || []).filter((p) => p.in === "query").map((p) => p.name),
      response,
    });
  }
}
operations.sort((a, b) => a.id.localeCompare(b.id));

const banner = "// Generated by scripts/generate.mjs from spec/openapi.json. Run `npm run generate`; do not edit.\n\n";
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/generated/schemas.ts", import.meta.url), banner + types.join("\n"));
writeFileSync(
  new URL("../src/generated/operations.ts", import.meta.url),
  `${banner}export const OPERATIONS = ${JSON.stringify(operations, null, 2)} as const;\n`,
);
console.log(`${types.length} types, ${operations.length} operations`);
